import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const supabase = path.join(root, 'supabase');
const read = (file) => fs.readFileSync(path.join(supabase, file), 'utf8');
const parts = [
  ['base-schema.sql', 'base tables'],
  ['security-schema.sql', 'security tables and guards'],
  ['security.sql', 'authorization, RLS, public projections and admin RPCs'],
  ['governance.sql', 'governance queue, correction RPCs and MFA recovery'],
  ['fresh-hooks.sql', 'Auth/review triggers and hooks'],
  ['import-upc.sql', 'atomic import RPC'],
  ['cloud/grants.sql', 'hosted Supabase application-role grants'],
];
const body = parts.map(([file, note]) => `-- Source: supabase/${file} (${note})\n${read(file)}`).join('\n\n');
const bundle = `-- UPC managed-Supabase schema bundle.
-- Generated by scripts/build-cloud-schema.mjs from the same sources as upc-init.sql,
-- but WITHOUT supabase/seed/upc-colleges.sql: formal colleges are loaded with
-- stable IDs from the WSL business-data export.
--
-- Apply to an EMPTY public schema in a new hosted project. This file does not
-- create or modify platform-owned auth/storage/realtime/vault schemas. It does
-- create triggers/hooks that reference auth.users and auth.sessions; those
-- objects must exist in the hosted project.
--
-- Auth Hook registration, MFA/TOTP and URL callbacks are console/Management API
-- configuration, not part of this SQL.
BEGIN;

${body}

COMMIT;
`;
const outDir = path.join(supabase, 'cloud');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'upc-cloud-schema.sql'), bundle);
console.log(`Wrote supabase/cloud/upc-cloud-schema.sql (${bundle.length} bytes)`);
