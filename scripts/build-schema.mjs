import fs from 'node:fs';

const read = (name) => fs.readFileSync(new URL('../supabase/' + name, import.meta.url), 'utf8');
const write = (name, sql) => fs.writeFileSync(new URL('../' + name, import.meta.url), sql);
const sqlString = (value) => `'${String(value).replace(/'/g, "''")}'`;
const sqlArray = (values) => `ARRAY[${values.map(sqlString).join(',')}]::text[]`;

const collegeData = JSON.parse(
  fs.readFileSync(new URL('../data/upc/colleges.json', import.meta.url), 'utf8'),
);
if (collegeData.schemaVersion !== 1 || !Array.isArray(collegeData.colleges) || collegeData.colleges.length === 0) {
  throw new Error('data/upc/colleges.json is missing a supported college list');
}

const seedRows = collegeData.colleges.map((college) =>
  `  (${sqlString(college.code)}, ${sqlString(college.name)}, ${sqlArray(college.aliases || [])})`,
).join(',\n');
const seed = `-- Generated by node scripts/build-schema.mjs from data/upc/colleges.json.
-- Source: ${collegeData.source}
-- Retrieved: ${collegeData.retrievedOn}
INSERT INTO public.colleges (code, name, aliases) VALUES
${seedRows}
ON CONFLICT (code) DO UPDATE
SET name = EXCLUDED.name,
    aliases = EXCLUDED.aliases;
`;

fs.mkdirSync(new URL('../supabase/seed/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../supabase/seed/upc-colleges.sql', import.meta.url), seed);

const parts = [
  ['base-schema.sql', read('base-schema.sql')],
  ['seed/upc-colleges.sql', seed],
  ['security.sql', read('security.sql')],
  ['fresh-hooks.sql', read('fresh-hooks.sql')],
  ['import-upc.sql', read('import-upc.sql')],
];

const init = `-- Generated by node scripts/build-schema.mjs. Edit the listed supabase/*.sql sources.
-- This is the complete clean-database initialization for the UPC deployment.
-- It is rating-v2 native and contains no old-school data, AI rules or notice tables.
--
-- Order: base tables -> official college dictionary -> authorization/RPCs ->
-- triggers/likes -> atomic import RPC.
BEGIN;

${parts.map(([name, sql]) => `-- Source: supabase/${name}\n${sql}`).join('\n\n')}

COMMIT;
`;

write('supabase_schema.sql', init);
write('supabase/upc-init.sql', init);

// Existing databases need both the new constraints and the matching importer.
// Reuse the clean-init RPC source so the two installation paths stay in sync.
const courseIdentityUpgrade = `-- Generated by node scripts/build-schema.mjs.
-- Edit supabase/upgrade-parts/course-code-identity.sql and supabase/import-upc.sql.
-- Non-destructive upgrade for initialized UPC databases: course identities and
-- import RPCs are updated together. Any failure rolls back the whole upgrade.
-- Run with psql -v ON_ERROR_STOP=1 -f supabase/upgrades/20261022-course-code-identity.sql
BEGIN;

${read('upgrade-parts/course-code-identity.sql')}

${read('import-upc.sql')}

COMMIT;
`;
fs.mkdirSync(new URL('../supabase/upgrades/', import.meta.url), { recursive: true });
write('supabase/upgrades/20261022-course-code-identity.sql', courseIdentityUpgrade);

const fourPointRatingUpgrade = `-- Generated by node scripts/build-schema.mjs.
-- Edit supabase/upgrade-parts/four-point-rating.sql.
-- Non-destructive upgrade for new 4.0–5.0 submissions. Historical 1–5 rows
-- remain readable and are not backfilled, truncated, or revalidated.
-- Run with psql -v ON_ERROR_STOP=1 -f supabase/upgrades/20261023-four-point-rating.sql
BEGIN;

${read('upgrade-parts/four-point-rating.sql')}

COMMIT;
`;
write('supabase/upgrades/20261023-four-point-rating.sql', fourPointRatingUpgrade);

console.log(`Generated clean schemas (${parts.length} parts), the course identity upgrade, and the four-point rating upgrade.`);
