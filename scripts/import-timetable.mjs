import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { buildPayload, hash, parseCSV } from './timetable/parse.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
export function generateSQL(payload, rollback = false, options = {}) {
  const read = name => fs.readFileSync(new URL(`./timetable/${name}`, import.meta.url), 'utf8');
  const literal = value => "'" + JSON.stringify(value).replaceAll("'", "''") + "'::jsonb";
  // Ordinary quoted SQL strings with standard_conforming_strings: data cannot
  // terminate dollar-quoted procedural bodies or become SQL instructions.
  return `-- Generated by scripts/import-timetable.mjs. Mode: ${rollback ? 'DRY RUN; all changes rolled back' : 'IMPORT; commit'}\n`
    + `BEGIN;\nSET LOCAL standard_conforming_strings=on;\nSET LOCAL lock_timeout='15s';\nSET LOCAL statement_timeout='300s';\n`
    + `SELECT pg_advisory_xact_lock(20260929,1);\n`
    + (options.preflightSQL || '')
    + read('schema.sql')
    + (options.payloadSetup || `\nCREATE TEMP TABLE _tt_payload(data jsonb NOT NULL) ON COMMIT DROP;\nINSERT INTO _tt_payload VALUES (${literal(payload)});\n`)
    + read('import.sql') + `\n${rollback ? 'ROLLBACK' : 'COMMIT'};\n`;
}

export function verificationSQL(payload) {
  const term = "'" + payload.term.replaceAll("'", "''") + "'";
  return `-- Read only; counts for this term (additional imports may increase them).\n`
    + `SELECT count(*) AS sections_expected_${payload.summary.sourceRows} FROM public.timetable_sections s JOIN public.terms t ON t.id=s.term_id WHERE t.year_term=${term};\n`
    + `SELECT count(*) AS meetings_expected_${payload.summary.meetings} FROM public.timetable_meetings m JOIN public.timetable_sections s ON s.id=m.section_id JOIN public.terms t ON t.id=s.term_id WHERE t.year_term=${term};\n`
    + `SELECT match_status,count(*) FROM public.timetable_teacher_links GROUP BY match_status;\n`
    + `SELECT source_key,source_name,source_department,candidate_ids FROM public.timetable_teacher_links WHERE match_status='pending' ORDER BY source_department,source_name;\n`
    + `SELECT t.id,t.name,a.name AS old_college,b.name AS new_college,u.changed_at FROM public.timetable_college_updates u JOIN public.teachers t ON t.id=u.teacher_id LEFT JOIN public.colleges a ON a.id=u.old_college_id JOIN public.colleges b ON b.id=u.new_college_id ORDER BY u.changed_at,t.name;\n`
    + `-- Per-section overlap: report source facts rather than resolve them automatically.\n`
    + `SELECT s.selection_code,a.source_index,b.source_index,a.weeks,b.weeks FROM public.timetable_meetings a JOIN public.timetable_meetings b ON a.section_id=b.section_id AND a.source_index<b.source_index AND a.weekday=b.weekday AND a.weeks && b.weeks AND a.period_start<=b.period_end AND b.period_start<=a.period_end JOIN public.timetable_sections s ON s.id=a.section_id JOIN public.terms t ON t.id=s.term_id WHERE t.year_term=${term};\n`
    + `-- Example: all scheduled lessons in week 7, Monday. Weeks-only lessons have NULL weekday.\n`
    + `SELECT * FROM public.timetable_schedule WHERE year_term=${term} AND weeks @> ARRAY[7] AND weekday=1 ORDER BY period_start,selection_code;\n`;
}

export function main(args = process.argv.slice(2)) {
  const { values } = parseArgs({ args, options: { csv: { type: 'string' }, config: { type: 'string' }, out: { type: 'string' }, help: { type: 'boolean' } } });
  if (values.help) {
    console.log('node scripts/import-timetable.mjs [--csv FILE] [--config FILE] [--out DIR]\nValidates CSV and generates dry-run/import SQL. No database connection or remote writes.');
    return;
  }
  const source = path.resolve(values.csv || path.join(root, 'schule2026-2027-1/courses.csv'));
  const configFile = path.resolve(values.config || path.join(root, 'scripts/timetable/config.json'));
  const output = path.resolve(values.out || path.join(root, 'schule2026-2027-1/import-output'));
  const sourceBytes = fs.readFileSync(source);
  const text = new TextDecoder('utf-8', { fatal: true }).decode(sourceBytes);
  const config = JSON.parse(fs.readFileSync(configFile, 'utf8'));
  const payload = buildPayload(parseCSV(text), config);
  const report = { ...payload.summary, issueCounts:payload.summary.issues, term: payload.term, csvSha256: hash(sourceBytes), configSha256: hash(fs.readFileSync(configFile)),
    remoteWrites: false, unknownDepartments: [...new Set(payload.courses.filter(c => !c.college).map(c => c.department))], issues: payload.issues };
  fs.mkdirSync(output, { recursive: true });
  fs.writeFileSync(path.join(output, '00-dry-run.sql'), generateSQL(payload, true));
  fs.writeFileSync(path.join(output, '01-import.sql'), generateSQL(payload));
  fs.writeFileSync(path.join(output, '02-verify.sql'), verificationSQL(payload));
  fs.writeFileSync(path.join(output, 'analysis-report.json'), JSON.stringify(report, null, 2) + '\n');
  fs.writeFileSync(path.join(output, 'teacher-keys.json'), JSON.stringify(payload.teachers, null, 2) + '\n');
  console.log(JSON.stringify({ output, ...payload.summary, csvSha256: report.csvSha256, remoteWrites: false }, null, 2));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
